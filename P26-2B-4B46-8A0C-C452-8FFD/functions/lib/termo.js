const dictionary = new Set([...answers.trim().split(/\s+/), ...solutions]);
const dayFormatter = new Intl.DateTimeFormat("en-CA", { timeZone: "America/Sao_Paulo",
  year: "numeric", month: "2-digit", day: "2-digit" });
const millisecondsInDay = 86_400_000;

export function normalizeGuess(value) {
  if (typeof value !== "string" || value.length > 30) return null;
  const word = value.trim().normalize("NFD").replace(/[\u0300-\u036f]/g, "").toUpperCase();
  return /^[A-Z]{5}$/.test(word) && dictionary.has(word) ? word : null;
}

export function gameClock(now = new Date()) {
  const parts = Object.fromEntries(dayFormatter.formatToParts(now)
    .map(({ type, value }) => [type, value]));
  const date = `${parts.year}-${parts.month}-${parts.day}`;
  const utcStart = Date.parse(date + "T00:00:00.000Z");
  // Brasília está em UTC−03:00 e não adota horário de verão.
  const nextResetAt = new Date(utcStart + millisecondsInDay + 3 * 3_600_000).toISOString();
  return { date, serverNow: now.toISOString(), nextResetAt };
}

export function previousDate(date) {
  return new Date(Date.parse(date + "T00:00:00.000Z") - millisecondsInDay)
    .toISOString().slice(0, 10);
}

export async function dailyAnswer(env, date) {
  const lookup = env.DB.prepare("SELECT answer FROM daily_words WHERE date = ?").bind(date);
  const existing = await lookup.first();
  if (existing) return existing.answer;

  const encoder = new TextEncoder();
  const key = await crypto.subtle.importKey("raw", encoder.encode(env.DAILY_WORD_SECRET),
    { name: "HMAC", hash: "SHA-256" }, false, ["sign"]);
  const digest = await crypto.subtle.sign("HMAC", key, encoder.encode(date));
  const index = new DataView(digest).getUint32(0) % solutions.length;

  await env.DB.prepare("INSERT OR IGNORE INTO daily_words (date, answer) VALUES (?, ?)")
    .bind(date, solutions[index]).run();
  return (await lookup.first()).answer;
}

export function scoreGuess(guess, answer) {
  const marks = Array(5).fill("absent");
  const remaining = new Map();

  for (let i = 0; i < 5; i++) {
    const letter = answer[i];
    if (guess[i] === letter) {
      marks[i] = "correct";
    } else {
      remaining.set(letter, (remaining.get(letter) || 0) + 1);
    }
  }

  for (let i = 0; i < 5; i++) {
    const letter = guess[i];
    const available = remaining.get(letter) || 0;
    if (marks[i] === "absent" && available > 0) {
      marks[i] = "present";
      remaining.set(letter, available - 1);
    }
  }
  return marks;
}
